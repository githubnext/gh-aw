package workflow

import (
	"fmt"

	"github.com/github/gh-aw/pkg/workflow/actions"
	"github.com/github/gh-aw/pkg/workflow/aw"
)

// ParseWorkflowDocument validates and resolves an AW source AST using the same
// schema, imports, defaults, diagnostics, and path rules as ParseWorkflowString.
// The document is not mutated. virtualPath anchors relative imports and errors.
func (c *Compiler) ParseWorkflowDocument(document *aw.Document, virtualPath string) (*WorkflowData, error) {
	content, err := aw.Emit(document)
	if err != nil {
		return nil, fmt.Errorf("serializing workflow document: %w", err)
	}
	return c.ParseWorkflowString(content, virtualPath)
}

// CompileDocument lowers an AW source AST to the native Actions execution AST.
// It runs the existing compiler rather than treating AW fields as native YAML.
// Authored expression strings retain the explicit edges generated by compilation.
func (c *Compiler) CompileDocument(document *aw.Document, virtualPath string) (*actions.Workflow, error) {
	data, err := c.ParseWorkflowDocument(document, virtualPath)
	if err != nil {
		return nil, err
	}
	content, err := c.CompileToYAML(data, virtualPath)
	if err != nil {
		return nil, err
	}
	result, err := actions.Parse([]byte(content))
	if err != nil {
		return nil, fmt.Errorf("building compiled workflow AST: %w", err)
	}
	return result, nil
}
