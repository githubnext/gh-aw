//go:build !integration

package workflow

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestCommentMemorySupportWorkflowDocumentsSpecRequirements(t *testing.T) {
	workflowPath := findRepoFile(t, filepath.Join(".github", "workflows", "comment-memory-support.md"))
	workflowBytes, err := os.ReadFile(workflowPath)
	require.NoError(t, err, "should read comment-memory support workflow")

	spec := string(workflowBytes)
	expectedRequirements := []string{
		"Add support for frontmatter field: `comment-memory`",
		"Support one or more memories (named and unnamed)",
		"Resolve execution context automatically (issue or pull request)",
		"Create memory comment on first run",
		"Update existing memory comment on subsequent runs",
		"Store memory using XML markers for robust parsing and identification",
		"Support default GitHub token",
		"Support custom GitHub token",
		"Support GitHub App authentication",
		"Support targeting external repositories when configured",
		"Apply standard body sanitization rules",
		"Enforce GitHub comment size limits",
		"`Generated by AI` footer",
	}

	for _, expected := range expectedRequirements {
		assert.Contains(t, spec, expected, "workflow spec should include requirement: %s", expected)
	}
}
