func TestDeployPRMessagePropagation(t *testing.T) {
	cmd := NewDeployCommand(func(string) error { return nil })
	require.NoError(t, cmd.Flags().Set("pr-message", "Deployment context."))
	opts, _, err := parseDeployCommandOptions(cmd, []string{"workflow"}, func(string) error { return nil })
	require.NoError(t, err)
	assert.Equal(t, "Deployment context.", opts.PRMessage)
	_, body := buildDeployPRMetadata([]string{"owner/repo/one", "owner/repo/two"}, "target/repo")
	assert.Contains(t, body, "- `owner/repo/one`")
	assert.Contains(t, body, "- `owner/repo/two`")
	assert.NotContains(t, body, "## Deployment steps")
	assert.NotContains(t, body, "## Review and next steps")
}

func TestDeployPRDescriptionOmitsLocalDirectories(t *testing.T) {
	local := filepath.Join(t.TempDir(), "private-project", "my-workflow.md")
	_, body := buildDeployPRMetadata([]string{local, "owner/repo/workflow@v1"}, "target/repo")
	assert.Contains(t, body, "- `my-workflow.md`")
	assert.Contains(t, body, "- `owner/repo/workflow@v1`")
	assert.NotContains(t, body, filepath.Dir(local))
	assert.NotContains(t, body, "private-project")
}
