package cli

import (
	"fmt"
	"strings"

	"github.com/spf13/cobra"
)

func addPRMessageFlag(cmd *cobra.Command) {
	cmd.Flags().String("pr-message", "", "Append a custom Markdown message to the generated pull request description")
}

func appendPRMessage(body, message string) string {
	if strings.TrimSpace(message) == "" {
		return body
	}
	return strings.TrimRight(body, "\n") + "\n\n" + message
}

func withPRFooter(body string) string {
	version := normalizeDisplayVersion(GetVersion())
	if version == "" {
		version = "vdev"
	}
	return strings.TrimRight(body, "\n") + fmt.Sprintf("\n\n---\n\nGenerated by gh aw %s\n", markdownText(version))
}

func buildInitPRBody(opts InitOptions) string {
	var body strings.Builder
	body.WriteString("## Summary\n\nPrepare this repository for [GitHub Agentic Workflows](https://github.github.com/gh-aw/) with editor integration and the selected setup options.\n\n## Repository setup\n\n")
	body.WriteString("- Configure VS Code settings for authoring agentic workflows.\n")
	if !opts.NoGitattributes {
		body.WriteString("- Configure `.gitattributes` for generated workflow files.\n")
	}
	if opts.Skill {
		body.WriteString("- Install the agentic-workflows dispatcher skill.\n")
	}
	if opts.Engine != "" {
		body.WriteString(fmt.Sprintf("- **Engine:** `%s`.\n", markdownText(opts.Engine)))
	}
	if opts.Engine == "copilot" {
		if opts.Agent {
			body.WriteString("- Install the GitHub Copilot custom agent.\n")
		}
		if opts.MCP {
			body.WriteString("- Configure the gh-aw MCP server and Copilot setup steps.\n")
		}
	}
	if opts.CodespaceEnabled {
		body.WriteString("- Configure a GitHub Codespaces devcontainer")
		if len(opts.CodespaceRepos) > 0 {
			body.WriteString(fmt.Sprintf(" with access to %s", joinCodeValues(opts.CodespaceRepos)))
		}
		body.WriteString(".\n")
	}
	body.WriteString("\n## Review and next steps\n\nReview the repository configuration, then merge to make the setup available to contributors. Add or author a Markdown workflow and compile it with `gh aw compile` when ready.\n")
	return appendPRMessage(body.String(), opts.PRMessage)
}

func buildTransferPRBody(info *PRInfo) string {
	var body strings.Builder
	if info.Body != "" {
		body.WriteString(info.Body)
		body.WriteString("\n\n---\n\n")
	}
	body.WriteString(fmt.Sprintf("## Transfer details\n\n**Transferred from:** [%s#%d](https://github.com/%s/pull/%d)\n\n", markdownText(info.SourceRepo), info.Number, info.SourceRepo, info.Number))
	body.WriteString(fmt.Sprintf("**Original Author:** @%s\n\n", markdownText(info.AuthorLogin)))
	body.WriteString("Apply the original pull request's changes as a single squashed commit, preserving its title and description. Review the patch for compatibility with this repository before merging.\n")
	return appendPRMessage(body.String(), info.PRMessage)
}
