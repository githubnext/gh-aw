package workqueue

import (
	"encoding/json"
	"fmt"
	"net/url"
	"regexp"
	"slices"
	"strings"
)

var issueSummaryClaimID = regexp.MustCompile(`^[A-Za-z0-9_.:-]{1,256}$`)

// Render the canonical summary sections from checked state, never an old comment
// or Work payload. Bound lists with an explicit link back to complete Git history.
func issueTransitionSummary(target issueTransitionTarget, state Projection, branch string) string {
	work := state.Works[target.WorkID]
	ledger := fmt.Sprintf("https://%s/%s/blob/%s/work-queue.jsonl", target.Resource.Host, state.Repository, url.PathEscape(branch))
	body := fmt.Sprintf("### 🧭 Work queue\n\nStatus: **%s**\n\n**Work:** `%s` (short ID) · [Checked Git ledger](%s)\n\n",
		target.Status, target.WorkID[:12], ledger)
	if work.State == "cancelled" {
		body += "Cancellation: `" + work.CancellationReason + "`. Cancellation is recorded in Git; it does not terminate a native worker.\n\n"
	} else if work.Barrier == "failed" {
		body += "Delivery needs attention (" + work.Disposition + "); Completion is not a verified Result.\n\n"
	} else if work.Barrier == "verified" {
		body += "The recorded delivery has been independently verified. A PR is not a merge.\n\n"
	}
	body += issueTransitionOutcomeLinks(work, target.Resource.Host) + "\n<details>\n<summary>Runs and Claims</summary>\n\n"
	return body + issueTransitionClaimHistory(target, state) + "\n</details>\n\n> [!NOTE]\n> Git is authoritative. Human Issue closure and status edits are not Work Results.\n\n" +
		"> Generated by `gh aw work-queue sync-issues` from the checked committed terminal request.\n"
}

func issueTransitionOutcomeLinks(work *WorkState, host string) string {
	var outcomes struct {
		Outputs []json.RawMessage `json:"outputs"`
	}
	var links strings.Builder
	if work.Barrier == "verified" && json.Unmarshal(work.Result, &outcomes) == nil {
		for _, output := range outcomes.Outputs {
			var descriptor struct {
				Resource struct {
					Kind, Host, Repository string
					Number                 json.Number
				}
			}
			if json.Unmarshal(output, &descriptor) != nil {
				continue
			}
			resource := descriptor.Resource
			if !repoPattern.MatchString(resource.Repository) || !decimalIdentity(resource.Number.String()) ||
				(resource.Kind != "issue" && resource.Kind != "pull_request") || (resource.Host != "" && resource.Host != host) {
				continue
			}
			path := "issues"
			if resource.Kind == "pull_request" {
				path = "pull"
			}
			line := fmt.Sprintf("Verified %s: https://%s/%s/%s/%s\n", resource.Kind, host, resource.Repository, path, resource.Number)
			if links.Len()+len(line) > 8*1024 {
				links.WriteString("Additional verified outcomes are retained in the checked Git ledger.\n")
				break
			}
			links.WriteString(line)
		}
	}
	return links.String()
}

func issueTransitionClaimHistory(target issueTransitionTarget, state Projection) string {
	work := state.Works[target.WorkID]
	var history strings.Builder
	historyBytes := 0
	if origin, ok := state.WorkCreators[work.WorkID]; ok && repoPattern.MatchString(origin.Repository) && decimalIdentity(origin.RunID) && origin.RunAttempt > 0 {
		line := fmt.Sprintf("- Admission: [View admitting run](https://%s/%s/actions/runs/%s/attempts/%d)\n",
			target.Resource.Host, origin.Repository, origin.RunID, origin.RunAttempt)
		history.WriteString(line)
		historyBytes += len(line)
	}
	claims := make([]string, 0)
	for id, claim := range state.Claims {
		if claim.WorkID == work.WorkID {
			claims = append(claims, id)
		}
	}
	slices.Sort(claims)
	for _, id := range claims {
		claim := state.Claims[id]
		dispatch := state.Dispatches[claim.DispatchID]
		if dispatch == nil || dispatch.Run == nil {
			continue
		}
		run := dispatch.Run
		if !repoPattern.MatchString(run.Repository) || !decimalIdentity(run.RunID) || run.RunAttempt < 1 || !issueSummaryClaimID.MatchString(id) {
			continue
		}
		line := fmt.Sprintf("- Claim `%s`: [View attempt](https://%s/%s/actions/runs/%s/attempts/%d)\n",
			id, target.Resource.Host, run.Repository, run.RunID, run.RunAttempt)
		if historyBytes+len(line) > 16*1024 {
			history.WriteString("Additional Runs and Claims are retained in the checked Git ledger.\n")
			break
		}
		history.WriteString(line)
		historyBytes += len(line)
	}
	if history.Len() == 0 {
		return "No authenticated worker run yet.\n"
	}
	return history.String()
}
