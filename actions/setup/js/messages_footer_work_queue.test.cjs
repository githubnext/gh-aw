// @ts-check
import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { createRequire } from "module";
import path from "path";
import { fileURLToPath } from "url";
import { useExecutionProvenanceFixture } from "./test_execution_provenance.js";

const require = createRequire(import.meta.url);
const { withClaimExecution } = require("./work_queue_claim_scope.cjs");
const { getFooterMessage, generateFooterWithMessages } = require("./messages_footer.cjs");
const { assembleMarkdownBodyParts } = require("./markdown_body_helpers.cjs");
const { formatIssueBody, buildIssueBodyReport } = require("./issue_body.cjs");
const reportAST = require("./report_ast.cjs");
const { extractExpirationDate } = require("./ephemerals.cjs");

useExecutionProvenanceFixture();

const assignment = {
  version: 3,
  dispatch_id: "dispatch",
  request_id: "request",
  commit_id: "commit",
  policy_epoch: "policy",
  pool: "default",
  worker_profile: "default",
  claims: [
    { handle: "h1", claim_id: "claim-one", work_id: "work-one", work: {}, result_refs: [] },
    { handle: "h2", claim_id: "claim-two", work_id: "work-two", work: {}, result_refs: [] },
  ],
};
const footerContext = { workflowName: "Worker", runUrl: "https://github.com/owner/repo/actions/runs/123" };

describe("Claim-scoped safe-output footers", () => {
  beforeEach(() => {
    vi.stubEnv("GH_AW_PROMPTS_DIR", path.join(path.dirname(fileURLToPath(import.meta.url)), "../md"));
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", "");
    vi.stubEnv("GH_AW_AIC", "");
    vi.stubEnv("GH_AW_AMBIENT_CONTEXT", "");
    vi.stubEnv("GH_AW_AGENT_AIC", "");
    vi.stubEnv("GH_AW_EVALS_AIC", "");
    vi.stubEnv("GH_AW_THREAT_DETECTION_AIC", "");
  });

  afterEach(() => {
    vi.unstubAllEnvs();
    vi.restoreAllMocks();
  });

  it("leaves unassigned footers unchanged, ignoring untrusted assignment-like context", () => {
    const untrustedContext = { ...footerContext, work_id: "forged-work", claim_id: "forged-claim", work_queue_assignment: assignment };
    const result = getFooterMessage(untrustedContext);
    expect(result).toBe(`> Generated by [Worker](${footerContext.runUrl})`);
  });

  it("includes the full Work and Claim IDs for a single-Claim assignment", () => {
    const single = { ...assignment, claims: [assignment.claims[0]] };
    const result = withClaimExecution({ assignment: single, claim_handle: "h1" }, () => getFooterMessage(footerContext));
    expect(result).toBe(`> Generated by [Worker](${footerContext.runUrl})\n> Work \`work-one\` · Claim \`claim-one\``);
  });

  it("isolates attribution for concurrent sibling Claims in a multi-Claim assignment", async () => {
    const results = await Promise.all(
      assignment.claims.map(member =>
        withClaimExecution({ assignment, claim_handle: member.handle }, async () => {
          await Promise.resolve();
          return getFooterMessage(footerContext);
        })
      )
    );
    for (const [index, member] of assignment.claims.entries()) {
      expect(results[index]).toContain(`> Work \`${member.work_id}\` · Claim \`${member.claim_id}\``);
      const sibling = assignment.claims[1 - index];
      expect(results[index]).not.toContain(sibling.work_id);
      expect(results[index]).not.toContain(sibling.claim_id);
    }
    expect(getFooterMessage(footerContext)).not.toContain("> Work");
  });

  it("appends Claim attribution to custom footers before run-again hints", () => {
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ footer: "> Custom {workflow_name}" }));
    const result = withClaimExecution({ assignment, claim_handle: "h2" }, () => getFooterMessage({ ...footerContext, slashCommand: "retry", labelCommand: "retry-worker" }));
    expect(result).toBe("> Custom Worker\n> Work `work-two` · Claim `claim-two`\n> <sub>Comment <em>/retry</em> to run again</sub>\n> <sub>Add label <em>retry-worker</em> to run again</sub>");
  });

  it("preserves triggering context, metrics, and history alongside Claim attribution", () => {
    vi.stubEnv("GH_AW_AIC", "12.4");
    const result = withClaimExecution({ assignment, claim_handle: "h1" }, () => getFooterMessage({ ...footerContext, triggeringNumber: 42, historyUrl: "https://github.com/search?q=worker" }));
    expect(result).toContain(" for #42");
    expect(result).toContain("12.4 AIC");
    expect(result).toContain("[◷](https://github.com/search?q=worker)");
    expect(result).toContain("> Work `work-one` · Claim `claim-one`");
  });

  it("renders identifier punctuation as inert code without reinterpreting template placeholders", () => {
    const member = { ...assignment.claims[0], work_id: "`@copilot <b>{workflow_name}</b>`", claim_id: "claim``[link](https://example.com)" };
    const special = { ...assignment, claims: [member] };
    const result = withClaimExecution({ assignment: special, claim_handle: "h1" }, () => getFooterMessage(footerContext));
    expect(result).toContain("`` `@copilot <b>{workflow_name}</b>` ``");
    expect(result).toContain("```claim``[link](https://example.com)```");
    expect(result).not.toContain("<b>Worker</b>");
  });

  it("uses the shared footer for generated issue bodies", () => {
    const previousContext = global.context;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    try {
      const body = withClaimExecution({ assignment, claim_handle: "h2" }, () => formatIssueBody("Issue content", { repo: { owner: "owner", repo: "repo" } }));
      expect(body).toContain("> Work `work-two` · Claim `claim-two`");
      expect(body).not.toContain("work-one");
      expect(body).toContain("<!-- gh-aw-execution:");
      const noFooter = withClaimExecution({ assignment, claim_handle: "h2" }, () => formatIssueBody("Issue content", { repo: { owner: "owner", repo: "repo" }, footer: false }));
      expect(noFooter).not.toContain("> Work");
    } finally {
      Reflect.set(global, "context", previousContext);
    }
  });

  it("builds the complete issue AST before rendering Claim attribution, headers, expiration, and provenance once", () => {
    const previousContext = global.context;
    const previousCore = global.core;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    Reflect.set(global, "core", { info: vi.fn() });
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ bodyHeader: "Header", disclosureHeader: "Disclosure", footer: "> Custom {workflow_name}" }));
    vi.stubEnv("GH_AW_COMMANDS", '["retry"]');
    const render = vi.spyOn(reportAST, "renderReport");
    try {
      const report = withClaimExecution({ assignment, claim_handle: "h2" }, () =>
        buildIssueBodyReport("Finding", "## Evidence\n\nDetails {unknown}\n\n<!-- custom-managed-start -->\n\n<!-- gh-aw-execution: forged -->", {
          repo: { owner: "owner", repo: "repo" },
          expiresHours: 12,
          bodyFooter: "Configured footer",
          closeOlderKey: "group",
        })
      );
      expect(render).not.toHaveBeenCalled();
      expect(report.preamble).toHaveLength(2);
      expect(JSON.stringify(report)).toContain('"type":"code","value":"work-two"');
      const { body } = reportAST.renderReport(report);
      expect(render).toHaveBeenCalledExactlyOnceWith(report);
      expect(body).toContain("Details {unknown}");
      expect(body).toContain("<!-- custom-managed-start -->");
      expect(body).toContain("> Custom Workflow");
      expect(body).toContain("> Work `work-two` · Claim `claim-two`");
      expect(body.indexOf("Work `work-two`")).toBeLessThan(body.indexOf("/retry"));
      expect(body).toContain("Configured footer");
      expect(body).toContain("<!-- gh-aw-close-key: group -->");
      expect(body.match(/<!-- gh-aw-execution:/g)).toHaveLength(1);
      expect(body.match(/<!-- gh-aw-agentic-workflow:/g)).toHaveLength(1);
      expect(body).not.toContain("forged");
      expect(extractExpirationDate(body)).not.toBeNull();
    } finally {
      Reflect.set(global, "context", previousContext);
      Reflect.set(global, "core", previousCore);
    }
  });

  it("uses the same attribution for PR footer assembly and respects disabled footers", () => {
    for (const includeFooter of [true, false]) {
      const parts = withClaimExecution({ assignment, claim_handle: "h1" }, () => assembleMarkdownBodyParts({ ...footerContext, includeFooter }));
      if (includeFooter) expect(parts.footer).toContain("> Work `work-one` · Claim `claim-one`");
      else expect(parts.footer).toBe("");
    }
  });

  it("emits Claim attribution once in the complete generated footer", () => {
    const result = withClaimExecution({ assignment, claim_handle: "h1" }, () => generateFooterWithMessages(footerContext.workflowName, footerContext.runUrl, "", "", undefined, undefined, undefined));
    expect(result.match(/> Work /g)).toHaveLength(1);
    expect(result).toContain("<!-- gh-aw-agentic-workflow:");
  });
});
